import assert from 'node:assert/strict'
import { ObjectiveTracker } from '../engine/script/ObjectiveTracker.ts'

const tracker = new ObjectiveTracker()
const events = []
tracker.subscribe(event => events.push([event.type, event.objective.id, event.objective.state]))
const gather = tracker.register({ id: 'gather', title: 'Gather samples', requiredProgress: 2 })
assert.equal(gather.state, 'active')
assert.equal(tracker.register({ id: 'deliver', prerequisites: ['gather'] }).state, 'locked')
tracker.validateGraph()
assert.equal(tracker.activate('deliver'), false)
assert.equal(tracker.addProgress('gather', 1), true)
assert.equal(tracker.get('gather')?.progress, 1)
assert.equal(tracker.addProgress('gather', 1), true)
assert.equal(tracker.isCompleted('gather'), true)
assert.equal(tracker.getState('deliver'), 'active', 'completing prerequisite unlocks dependent objective')
assert.equal(tracker.complete('deliver'), true)
assert.equal(tracker.list().map(item => item.state).join(','), 'completed,completed')
assert.ok(events.some(([type, id]) => type === 'activated' && id === 'deliver'))
assert.equal(tracker.remove('gather'), false, 'cannot remove a prerequisite still referenced by another objective')
assert.equal(tracker.reset(), undefined)
assert.equal(tracker.getState('gather'), 'active')
assert.equal(tracker.getState('deliver'), 'locked')
assert.equal(tracker.addProgress('gather', 0), false)
assert.equal(tracker.fail('gather'), true)
assert.equal(tracker.fail('gather'), false)
assert.equal(tracker.remove('deliver'), true)
assert.throws(() => tracker.register({ id: 'bad', requiredProgress: 0 }), /requiredProgress/)
const cyclic = new ObjectiveTracker()
cyclic.register({ id: 'a', prerequisites: ['b'] })
cyclic.register({ id: 'b', prerequisites: ['a'] })
assert.throws(() => cyclic.validateGraph(), /cycle/)
const missing = new ObjectiveTracker()
missing.register({ id: 'needs-missing', prerequisites: ['missing'] })
assert.throws(() => missing.validateGraph(), /missing prerequisite/)
console.log('Objective tracker self-test passed.')
