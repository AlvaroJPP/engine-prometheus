import assert from 'node:assert/strict'
import { StatusEffectRuntime } from '../engine/runtime/StatusEffectRuntime.ts'

const effects = new StatusEffectRuntime(3)
assert.equal(effects.apply('player', 'poison', 2, { tickIntervalSeconds: 1 })?.type, 'applied')
assert.equal(effects.has('player', 'poison'), true)
assert.deepEqual(effects.update(0.5), [])
const firstTick = effects.update(0.5)
assert.deepEqual(firstTick.map(event => [event.type, event.effectId, event.tickIndex]), [['tick', 'poison', 1]])
const poisonEnd = effects.update(1)
assert.deepEqual(poisonEnd.map(event => event.type), ['tick', 'expired'])
assert.equal(effects.has('player', 'poison'), false)

effects.apply('player', 'focus', 4, { stackPolicy: 'stack', maxStacks: 2, metadata: { source: 'potion' } })
effects.apply('player', 'focus', 4, { stackPolicy: 'stack', maxStacks: 2 })
assert.equal(effects.get('player', 'focus')?.stacks, 2)
effects.apply('player', 'focus', 1, { stackPolicy: 'stack', maxStacks: 2 })
assert.equal(effects.get('player', 'focus')?.stacks, 2)
assert.equal(effects.get('player', 'focus')?.remainingSeconds, 1)
assert.equal(effects.apply('player', 'focus', 3, { stackPolicy: 'replace' })?.stacks, 1)
assert.equal(effects.get('player', 'focus')?.metadata.source, undefined)
assert.equal(effects.remove('player', 'focus')?.type, 'removed')
assert.equal(effects.remove('player', 'focus'), null)
effects.apply('enemy', 'slow', 5)
assert.deepEqual(effects.removeOwner('enemy').map(event => event.type), ['removed'])
assert.equal(effects.apply('', 'bad', 2), null)
assert.equal(effects.apply('player', 'bad', 0), null)
assert.equal(effects.apply('player', 'bad', 2, { tickIntervalSeconds: 0 }), null)
assert.throws(() => new StatusEffectRuntime(0), /maxCatchUpTicks/)
console.log('Status effect runtime self-test passed.')
